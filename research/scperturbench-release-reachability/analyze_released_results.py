"""Measure reachability of the reported baseReg/baseMLP defect in released results.

This DOES NOT compute corrected predictions. It verifies the affected scripts,
repository provenance text, and cellular-context result tables at one immutable
scPerturBench commit, then inventories the affected baseline rows.
"""
from __future__ import annotations
import csv
import hashlib
import io
import json
import math
import statistics
from collections import Counter
from pathlib import Path
from urllib.request import Request, urlopen

COMMIT = "6e24e7a9827e55d4567d2139427be9af0d1e7a6c"
BASE = f"https://raw.githubusercontent.com/bm2-lab/scPerturBench/{COMMIT}/"
FILES = {
    "iid_top100": ("Results/Cellular_context_iid/cellular_iid_performance_top100.csv", "89c9cf9238cbe28d5815bff5cda8f597d347813a"),
    "iid_top5000": ("Results/Cellular_context_iid/cellular_iid_performance_top5000.csv", "0ed3dfa196b06c5faa906f73c776cd1c5ad46ebe"),
    "ood_top100": ("Results/Cellular_context_ood/cellular_ood_performance_top100.csv", "2afcc0ec620b139001303a32878f976f2a0eca24"),
    "ood_top5000": ("Results/Cellular_context_ood/cellular_ood_performance_top5000.csv", "4e0ee77d1c9de758ad83f368a0269db13decd4d5"),
}
SOURCES = {
    "iid_baseReg": ("Cellular_context_generalization/i.i.d./baseReg.py", "9363c6a2abd3e349bccc47cb9cec69bdafa6f173"),
    "iid_baseMLP": ("Cellular_context_generalization/i.i.d./baseMLP.py", "f58268f2ee0c04ed161bd7d16525b5471430d0ee"),
    "ood_baseReg": ("Cellular_context_generalization/o.o.d./baseReg.py", "fa44ff012bb5723d4a6ac57a8d07e2041a5f04bd"),
    "ood_baseMLP": ("Cellular_context_generalization/o.o.d./baseMLP.py", "ce29997687318b151bf7cb983fd7c8a47f1affef"),
}
README = ("README.md", "21c3c41abd0ebf8e2525c16d64e5e78e0c846084")
TARGETS = {"baseReg", "baseMLP"}
OUT = Path(__file__).resolve().parent / "result.json"


def git_blob_sha(raw: bytes) -> str:
    return hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()


def fetch(path: str, expected: str, limit: int = 20_000_000) -> tuple[bytes, str]:
    url = BASE + path
    with urlopen(Request(url, headers={"User-Agent": "CheerfulDuck-scientific-code-audit"}), timeout=45) as r:
        raw = r.read(limit + 1)
    if len(raw) > limit:
        raise RuntimeError(f"Unexpectedly large file: {path}")
    actual = git_blob_sha(raw)
    if actual != expected:
        raise RuntimeError(f"Git blob mismatch for {path}: {actual} != {expected}")
    return raw, url


def as_float(value: str):
    try:
        v = float(value)
        return v if math.isfinite(v) else None
    except (TypeError, ValueError):
        return None


def summarize_numeric(values):
    vals = [v for v in (as_float(x) for x in values) if v is not None]
    if not vals:
        return None
    return {"n": len(vals), "min": min(vals), "median": statistics.median(vals),
            "mean": statistics.fmean(vals), "max": max(vals)}


def verify_sources():
    records = []
    for name, (path, expected) in SOURCES.items():
        raw, url = fetch(path, expected, 100_000)
        text = raw.decode("utf-8", errors="strict")
        # Pin both ends of the mismatch rather than relying only on a filename.
        assert "return annList_Pertb, annList_control" in text, path
        assert "Xtr_anndata, ytr_anndata = generatePairedSample" in text, path
        if "baseReg" in name:
            assert "Ridge(" in text and ".fit(Xtr, ytr)" in text, path
        else:
            assert "trainModel" in text, path
        records.append({"name": name, "path": path, "url": url, "bytes": len(raw),
                        "git_blob_sha1": git_blob_sha(raw), "sha256": hashlib.sha256(raw).hexdigest()})
    raw, url = fetch(*README, limit=100_000)
    text = raw.decode("utf-8", errors="strict")
    # Repository-provided provenance: these scenario directories are described as the
    # scripts used, and Results as benchmark performance results generated by methods.
    assert "contained the script used in the i.i.d setting" in text
    assert "contained the script used in the o.o.d. setting" in text
    assert "contained the performance results generated by the benchmarking methods" in text
    return records, {"path": README[0], "url": url, "bytes": len(raw),
                     "git_blob_sha1": git_blob_sha(raw), "sha256": hashlib.sha256(raw).hexdigest(),
                     "asserted_provenance_statements": [
                         "i.i.d directory described as containing the script used in the i.i.d setting",
                         "o.o.d directory described as containing the script used in the o.o.d setting",
                         "Results described as containing performance results generated by benchmarking methods",
                     ]}


def analyze(name: str, path: str, expected: str):
    raw, url = fetch(path, expected)
    reader = csv.DictReader(io.StringIO(raw.decode("utf-8-sig")))
    rows = list(reader); fields = reader.fieldnames or []
    if not rows or not fields:
        raise RuntimeError(f"No rows/headers: {path}")
    scores = {f: sum((r.get(f) or "") in TARGETS for r in rows) for f in fields}
    method_col, hits = max(scores.items(), key=lambda x: x[1])
    if hits == 0:
        raise RuntimeError(f"Could not find baseReg/baseMLP values in {path}")
    method_counts = Counter((r.get(method_col) or "") for r in rows)
    target_rows = [r for r in rows if (r.get(method_col) or "") in TARGETS]
    dataset_cols = [f for f in fields if "dataset" in f.lower() or "data_set" in f.lower()]
    rank_cols = [f for f in fields if "rank" in f.lower()]
    by_method = {}
    for method in sorted(TARGETS):
        mr = [r for r in rows if (r.get(method_col) or "") == method]
        by_method[method] = {
            "rows": len(mr),
            "datasets": {f: sorted(set((r.get(f) or "") for r in mr)) for f in dataset_cols},
            "overall_rank": summarize_numeric([(r.get("Rank") or "") for r in mr]) if "Rank" in fields else None,
            "rank_columns": {f: summarize_numeric([(r.get(f) or "") for r in mr]) for f in rank_cols},
        }
    return {"name": name, "path": path, "url": url, "bytes": len(raw),
            "git_blob_sha1": git_blob_sha(raw), "sha256": hashlib.sha256(raw).hexdigest(),
            "rows_total": len(rows), "columns": fields, "method_column": method_col,
            "method_counts": dict(method_counts), "affected_baseline_rows": len(target_rows),
            "by_method": by_method}


def main():
    sources, readme = verify_sources()
    summaries = [analyze(name, path, sha) for name, (path, sha) in FILES.items()]
    total_reg = sum(s["by_method"]["baseReg"]["rows"] for s in summaries)
    total_mlp = sum(s["by_method"]["baseMLP"]["rows"] for s in summaries)
    datasets = sorted(set().union(*[
        set(s["by_method"]["baseReg"]["datasets"].get("DataSet", [])) for s in summaries
    ]))
    result = {
        "scope": "Same-commit reachability inventory: affected cellular-context scripts plus released result tables; no corrected predictions or leaderboard computed.",
        "scperturbench_commit": COMMIT,
        "source_verification": sources,
        "repository_provenance": readme,
        "files": summaries,
        "totals": {"affected_baseline_rows": total_reg + total_mlp,
                   "baseReg_rows": total_reg, "baseMLP_rows": total_mlp,
                   "datasets": datasets, "dataset_count": len(datasets)},
    }
    OUT.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({"commit": COMMIT, "source_files_verified": len(sources),
                      "repository_provenance": readme["asserted_provenance_statements"],
                      "totals": result["totals"],
                      "files": [{"name": s["name"], "rows_total": s["rows_total"],
                                 "affected_baseline_rows": s["affected_baseline_rows"],
                                 "baseReg_overall_rank": s["by_method"]["baseReg"]["overall_rank"],
                                 "baseMLP_overall_rank": s["by_method"]["baseMLP"]["overall_rank"]}
                                for s in summaries]}, indent=2))
    print("PASS: defective baseline scripts and released cellular-context result rows are verified at the same scPerturBench commit.")

if __name__ == "__main__":
    main()
